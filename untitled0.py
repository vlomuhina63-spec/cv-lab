import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import confusion_matrix, classification_report
import seaborn as sns

# 1. Загрузка CIFAR-10 и выбор 3 классов
(x_train, y_train), (x_test, y_test) = tf.keras.datasets.cifar10.load_data()
classes = [2, 3, 5]  # bird, cat, dog
names = ['bird', 'cat', 'dog']

def filter_data(x, y):
    mask = np.isin(y.flatten(), classes)
    return x[mask], y[mask]

x_train, y_train = filter_data(x_train, y_train)
x_test, y_test = filter_data(x_test, y_test)

# Перекодировка меток в 0,1,2
mapping = {c: i for i, c in enumerate(classes)}
y_train = np.array([mapping[v] for v in y_train.flatten()])
y_test = np.array([mapping[v] for v in y_test.flatten()])

# Нормализация
x_train = x_train / 255.0
x_test = x_test / 255.0

# 2. Модель MobileNetV2 + transfer learning
base = tf.keras.applications.MobileNetV2(input_shape=(32,32,3), include_top=False, weights='imagenet')
base.trainable = False

model = tf.keras.Sequential([
    base,
    tf.keras.layers.GlobalAveragePooling2D(),
    tf.keras.layers.Dense(128, activation='relu'),
    tf.keras.layers.Dropout(0.3),
    tf.keras.layers.Dense(3, activation='softmax')
])

model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

# 3. Обучение
history = model.fit(x_train, y_train, epochs=10, batch_size=32, validation_split=0.2)

# 4. Оценка
loss, acc = model.evaluate(x_test, y_test)
print(f'Test Accuracy: {acc*100:.2f}%')

y_pred = np.argmax(model.predict(x_test), axis=1)
print(classification_report(y_test, y_pred, target_names=names))

# 5. Confusion matrix
cm = confusion_matrix(y_test, y_pred)
plt.figure(figsize=(6,5))
sns.heatmap(cm, annot=True, fmt='d', xticklabels=names, yticklabels=names)
plt.savefig('confusion_matrix.png')
plt.show()

# 6. Графики
plt.plot(history.history['accuracy'], label='train')
plt.plot(history.history['val_accuracy'], label='val')
plt.legend(); plt.savefig('accuracy.png'); plt.show()

plt.plot(history.history['loss'], label='train')
plt.plot(history.history['val_loss'], label='val')
plt.legend(); plt.savefig('loss.png'); plt.show()

# 7. Сохранение модели
model.save('model.h5')